#!/bin/sh
# Regenerate src/harness_table.rs from the skills CLI's table of supported agents.
#   sh scripts/sync-harnesses.sh [agents.md]
set -eu
src=https://raw.githubusercontent.com/vercel-labs/skills/main/docs/agents.md
out=$(cd "$(dirname "$0")/.." && pwd)/src/harness_table.rs
if [ $# -gt 0 ]; then table=$(cat "$1"); else table=$(curl -fsSL "$src"); fi

{
  echo "// Generated by scripts/sync-harnesses.sh from"
  echo "// $src ($(date -u +%F)). Do not edit."
  echo "pub const HARNESSES: &[Harness] = &["
  printf '%s\n' "$table" | sed -n '/supported-agents:start/,/supported-agents:end/p' | awk -F'|' '
    function dir(cell) {
      gsub(/[` ]/, "", cell); sub(/\/$/, "", cell)
      return (cell ~ /^N\/A/ || cell == "") ? "None" : "Some(\"" cell "\")"
    }
    NF >= 5 && $3 ~ /`/ && $3 !~ /--agent/ {
      project = dir($4); user = dir($5)
      n = split($3, ids, ",")
      for (i = 1; i <= n; i++) {
        id = ids[i]; gsub(/[` ]/, "", id)
        printf "    Harness { id: \"%s\", project: %s, user: %s },\n", id, project, user
      }
    }'
  echo "];"
} > "$out.tmp"
mv "$out.tmp" "$out"
echo "wrote $(grep -c 'Harness {' "$out") harnesses to $out"
